func (is *Installer) InstallAqua(ctx context.Context, logger *slog.Logger, version string) error {
	pkg := &config.Package{
		Package: &aqua.Package{
			Name:    "aquaproj/aqua",
			Version: version,
		},
		PackageInfo: &registry.PackageInfo{
			Type:               pkgTypeGitHubRelease,
			RepoOwner:          "aquaproj",
			RepoName:           pkgNameAqua,
			VersionConstraints: `false`,
			VersionOverrides:   aquaVersionOverrides(),
		},
	}

	pkgInfo, err := pkg.PackageInfo.Override(logger, pkg.Package.Version, is.runtime)
	if err != nil {
		return fmt.Errorf("evaluate version constraints: %w", err)
	}
	pkg.PackageInfo = pkgInfo

	logger = logger.With(
		"package_name", pkg.Package.Name,
		"package_version", pkg.Package.Version,
		"registry", pkg.Package.Registry,
	)
	if err := is.InstallPackage(ctx, logger, &ParamInstallPackage{
		Checksums:     checksum.New(), // Check aqua's checksum but not update aqua-checksums.json
		Pkg:           pkg,
		DisablePolicy: true,
	}); err != nil {
		return err
	}

	exePath, err := pkg.ExePath(is.rootDir, &registry.File{
		Name: pkgNameAqua,
	}, is.runtime)
	if err != nil {
		return fmt.Errorf("get the executable file path: %w", err)
	}

	if is.runtime.GOOS == goosWindows {
		return is.copyAquaOnWindows(exePath)
	}

	// create a symbolic link
	a, err := filepath.Rel(filepath.Join(is.rootDir, "bin"), exePath)
	if err != nil {
		return fmt.Errorf("get a relative path: %w", err)
	}

	return is.createLink(logger, filepath.Join(is.rootDir, "bin", pkgNameAqua), a)
}

func (is *Installer) copyAquaOnWindows(exePath string) error {
	// https://github.com/orgs/aquaproj/discussions/2510
	// https://stackoverflow.com/questions/1211948/best-method-for-implementing-self-updating-software
	// https://github.com/aquaproj/aqua/issues/2918
	dest := filepath.Join(is.rootDir, "bin", "aqua.exe")
	f, err := osfile.Exists(dest)
	if err != nil {
		return err //nolint:wrapcheck
	}
	if f {
		// A temporary file elsewhere can't be used
		// > The system cannot move the file to a different disk drive
		tempDir := filepath.Join(is.rootDir, "temp")
		if err := osfile.MkdirAll(tempDir); err != nil {
			return fmt.Errorf("create a temporary directory: %w", err)
		}
		if err := os.Rename(dest, filepath.Join(tempDir, "aqua.exe")); err != nil {
			return fmt.Errorf("rename aqua.exe to update: %w", err)
		}
	}
	if err := is.linker.Hardlink(exePath, dest); err != nil {
		return fmt.Errorf("create a hard link to aqua.exe: %w", err)
	}
	return nil
}

// aquaVersionOverrides returns aqua's version overrides.
// They are generated by `aqua gr aquaproj/aqua`.
func aquaVersionOverrides() []*registry.VersionOverride {
	cosignSig := aquaCosignWithSignature()
	cosignBundle := aquaCosignWithBundle("aqua_{{trimV .Version}}_checksums.txt.bundle")
	cosignSigstore := aquaCosignWithBundle("aqua_{{trimV .Version}}_checksums.txt.sigstore.json")
	windowsZip := []*registry.Override{
		{
			GOOS:   goosWindows,
			Format: "zip",
		},
	}
	linuxDarwin := newAquaVersionOverride(`semver("<= 1.10.2")`, nil, false, nil)
	linuxDarwin.SupportedEnvs = registry.SupportedEnvs{"linux", "darwin"}
	return []*registry.VersionOverride{
		newAquaVersionOverride(`Version in ["v1.25.1-2", "v1.30.2-2"]`, cosignSig, false, nil),
		newAquaVersionOverride(`Version == "v1.30.2-1"`, cosignSig, true, nil),
		newAquaVersionOverride(`Version == "v2.0.0-0"`, nil, false, nil),
		newAquaVersionOverride(`Version == "v2.21.1"`, cosignSig, false, windowsZip),
		newAquaVersionOverride(`Version == "v2.65.0"`, cosignSigstore, false, windowsZip),
		newAquaVersionOverride(`semver("<= 0.1.0-6")`, nil, false, []*registry.Override{
			{
				GOOS: goosWindows,
				Replacements: registry.Replacements{
					"arm64": "arm",
				},
			},
		}),
		newAquaVersionOverride(`semver("<= 0.2.0")`, nil, false, nil),
		linuxDarwin,
		newAquaVersionOverride(`semver("<= 1.25.1-6")`, nil, false, nil),
		newAquaVersionOverride(`semver("<= 1.25.1-9")`, nil, true, nil),
		newAquaVersionOverride(`semver("<= 1.25.2")`, nil, false, nil),
		newAquaVersionOverride(`semver("<= 1.30.2-0")`, nil, true, nil),
		newAquaVersionOverride(`semver("<= 2.16.5-2")`, cosignSig, true, nil),
		newAquaVersionOverride(`semver("<= 2.25.0")`, cosignSig, true, windowsZip),
		newAquaVersionOverride(`semver("<= 2.25.1-4")`, cosignSig, false, windowsZip),
		newAquaVersionOverride(`semver("<= 2.55.0")`, cosignSig, true, windowsZip),
		newAquaVersionOverride(`semver("<= 2.60.0")`, cosignBundle, true, windowsZip),
		newAquaVersionOverride(`true`, cosignSigstore, true, windowsZip),
	}
}

func newAquaVersionOverride(versionConstraint string, cosign *registry.Cosign, slsa bool, overrides []*registry.Override) *registry.VersionOverride {
	vo := &registry.VersionOverride{
		VersionConstraints: versionConstraint,
		Asset:              "aqua_{{.OS}}_{{.Arch}}.{{.Format}}",
		Format:             "tar.gz",
		Overrides:          overrides,
		Files: []*registry.File{
			{
				Name: pkgNameAqua,
			},
		},
		Checksum: &registry.Checksum{
			Type:       pkgTypeGitHubRelease,
			Asset:      "aqua_{{trimV .Version}}_checksums.txt",
			FileFormat: algoTypeRegexp,
			Algorithm:  algoSHA256,
			Pattern: &registry.ChecksumPattern{
				Checksum: regexpSHA256,
				File:     regexpSHA256WithFile,
			},
			Cosign: cosign,
		},
	}
	if slsa {
		provAsset := "multiple.intoto.jsonl"
		vo.SLSAProvenance = &registry.SLSAProvenance{
			Type:  pkgTypeGitHubRelease,
			Asset: &provAsset,
		}
	}
	return vo
}

const (
	goosWindows                   = "windows"
	aquaCertificateIdentityRegexp = `^https://github\.com/aquaproj/aqua/\.github/workflows/.+\.ya?ml@refs/tags/\Q{{.Version}}\E$`
	githubActionsOIDCIssuer       = "https://token.actions.githubusercontent.com"
)

func aquaCosignWithSignature() *registry.Cosign {
	return &registry.Cosign{
		Opts: []string{
			"--certificate",
			"https://github.com/aquaproj/aqua/releases/download/{{.Version}}/aqua_{{trimV .Version}}_checksums.txt.pem",
			"--certificate-identity-regexp",
			aquaCertificateIdentityRegexp,
			"--certificate-oidc-issuer",
			githubActionsOIDCIssuer,
			"--signature",
			"https://github.com/aquaproj/aqua/releases/download/{{.Version}}/aqua_{{trimV .Version}}_checksums.txt.sig",
		},
	}
}

func aquaCosignWithBundle(asset string) *registry.Cosign {
	return &registry.Cosign{
		Opts: []string{
			"--certificate-identity-regexp",
			aquaCertificateIdentityRegexp,
			"--certificate-oidc-issuer",
			githubActionsOIDCIssuer,
		},
		Bundle: &registry.DownloadedFile{
			Type:  pkgTypeGitHubRelease,
			Asset: &asset,
		},
	}
}
